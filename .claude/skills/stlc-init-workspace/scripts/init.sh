#!/usr/bin/env bash
# init.sh — Initialise qa-artifacts workspace (macOS / Linux)
# Run from the project root: bash .claude/skills/stlc-init-workspace/scripts/init.sh
# Safe to re-run — existing files are never overwritten.
# Pass --reset to delete and recreate qa-artifacts/

set -euo pipefail

BASE="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../../.." && pwd)"   # project root
RESET=false
[[ "${1:-}" == "--reset" ]] && RESET=true

# ── Optionally reset ─────────────────────────────────────────────────────────
if $RESET && [ -d "$BASE/qa-artifacts" ]; then
  rm -rf "$BASE/qa-artifacts"
  echo "  qa-artifacts/ removed."
fi

# ── Folders ──────────────────────────────────────────────────────────────────
FOLDERS=(
  "requirements"
  "qa-artifacts/0-sprint-tickets"
  "qa-artifacts/1-requirements-analysis"
  "qa-artifacts/2-test-plan"
  "qa-artifacts/3-test-cases"
  "qa-artifacts/4-execution-results"
  "qa-artifacts/4-execution-results/screenshots"
  "qa-artifacts/5-testing-report"
  "qa-artifacts/base-test"
  "qa-artifacts/qa-config"
  "qa-artifacts/qa-docs"
)

for f in "${FOLDERS[@]}"; do
  target="$BASE/$f"
  if [ ! -d "$target" ]; then
    mkdir -p "$target"
    echo "  Created : $f"
  else
    echo "  Exists  : $f"
  fi
done

# ── README files ─────────────────────────────────────────────────────────────
write_readme() {
  local path="$BASE/$1"
  local content="$2"
  if [ ! -f "$path" ]; then
    echo "$content" > "$path"
    echo "  README  : $1"
  fi
}

write_readme "qa-artifacts/0-sprint-tickets/README.md" \
"# 0 — Sprint Tickets
Generated by: tracker-fetch-sprint-tickets
Output files: sprint<N>-tickets.md (one file per sprint fetched)

Each file contains the full ticket list for a sprint, grouped by status."

write_readme "requirements/README.md" \
"# requirements/

Place your requirement \`.md\` files here before starting the STLC pipeline.

Each file should describe features using user stories, acceptance criteria, and out-of-scope statements.

**Next step:** Run the \`stlc-requirements-analyst\` skill."

write_readme "qa-artifacts/1-requirements-analysis/README.md" \
"# 1 — Requirements Analysis
Generated by: stlc-requirements-analyst
Output file:  requirements-analysis.md"

write_readme "qa-artifacts/2-test-plan/README.md" \
"# 2 — Test Plan
Generated by: stlc-test-plan-designer
Output file:  test-plan.md"

write_readme "qa-artifacts/3-test-cases/README.md" \
"# 3 — Test Cases
Generated by: stlc-testcase-designer
Output file:  test-cases.md"

write_readme "qa-artifacts/4-execution-results/README.md" \
"# 4 — Execution Results
Generated by: stlc-manual-executor
Output files: execution-log.md · screenshots/"

write_readme "qa-artifacts/4-execution-results/screenshots/README.md" \
"# screenshots/
Browser screenshots captured during test execution.
Naming: TC-XXX-[pass|fail]-stepN.png"

write_readme "qa-artifacts/5-testing-report/README.md" \
"# 5 — Testing Report
Generated by: stlc-bug-reporter + stlc-test-reporter
Output files: bug-report.md · test-report.md"

write_readme "qa-artifacts/qa-docs/README.md" "# qa-docs/ — domain and feature knowledge

This folder is the \`domain\` knowledge source named in \`qa-config/knowledge.md\`.
Write one file per feature or business area, and keep three things apart in each:

- **What the spec says** — cite the ticket or requirement.
- **What a run observed** — cite the test case, the date, and the screenshot.
- **What is still unknown** — cite the open question and who owns it.

A test-case designer that cannot tell those apart will write cases that assert a bug is
correct behaviour. Nothing here is generated: this is the knowledge the team accumulates,
and it is the only artifact folder that outlives a single test cycle.

Once the first file exists, set the \`domain\` row in \`qa-config/knowledge.md\` to
\`active\`."

# ── qa-config/tools.md — project tool registry ───────────────────────────────
TOOLS_REGISTRY="$BASE/qa-artifacts/qa-config/tools.md"
if [ ! -f "$TOOLS_REGISTRY" ]; then
  cat > "$TOOLS_REGISTRY" << 'EOF'
# Project Tool Registry

**Owned by the QA on this project — not by the skill framework.**

Every skill that touches a tracker, a browser, or a notification channel reads this
file *first* to decide which provider to call. Skills never name a provider
themselves; they name a **capability** (`tracker.get_ticket`) and let this table
resolve it to a real tool.

To move this project onto a different tracker, change the `tracker` row below. No
skill file changes.

---

## 1. Bindings

| Capability group | Provider | Access | Adapter | State |
|---|---|---|---|---|
| `tracker` | _(choose one)_ | — | — | unbound |
| `browser` | `playwright` | `mcp__playwright__*` | `.claude/skills/providers/playwright.md` | active |
| `notify` | `none` | — | — | disabled |

**`State` values:** `active` (use it), `disabled` (skip the step and say so — not a
failure), `unbound` (no provider chosen yet — ask the user before doing anything).

A capability group missing from this table is `unbound`.

Adapters available out of the box: `openproject`, `jira` (tracker) · `playwright`
(browser) · `slack` (notify). See `.claude/skills/providers/`.

---

## 2. `tracker` settings

Fill these in once a tracker is chosen, then set its row above to `active`.

| Setting | Value |
|---|---|
| `base_url` | _(tracker URL)_ |
| `default_project` | _(project name or key)_ |
| `credentials` | _(name the env var — never paste a token here)_ |

## 3. `browser` settings

| Setting | Value |
|---|---|
| `screenshot_dir` | `qa-artifacts/4-execution-results/screenshots` |
| `admin_viewport` | 1280 x 800 |
| `member_viewport` | 390 x 844 |

## 4. `notify` settings

Disabled. To enable, set the `notify` row to a provider with an adapter, and add the
target channel here.

---

## Rules

- **Never hardcode a credential here.** Name the environment variable that holds it.
- A skill that finds its capability `unbound` must ask the user which provider to use
  and offer to add the row — it must never guess, and never report the operation done.
- When a provider is added or removed, this file and the adapter change together.
EOF
  echo "  Created : qa-artifacts/qa-config/tools.md  (edit this — bind your tracker)"
else
  echo "  Exists  : qa-artifacts/qa-config/tools.md"
fi

# ── qa-config/knowledge.md — project knowledge registry ──────────────────────
KNOWLEDGE_REGISTRY="$BASE/qa-artifacts/qa-config/knowledge.md"
if [ ! -f "$KNOWLEDGE_REGISTRY" ]; then
  cat > "$KNOWLEDGE_REGISTRY" << 'KEOF'
# Project Knowledge Registry

**Owned by the QA on this project - not by the skill framework.**

Every skill that needs standing knowledge about the application under test reads this
file *first* to decide which files to open. Skills never hardcode a knowledge path;
they name a **source ID** (`navigation`, `domain`) and let this table resolve it.

The resolution rule, the source-ID vocabulary and the rules for skill authors are in
`.claude/skills/knowledge-sources.md`. This file holds only *this project's* answers.

**Application under test:** _(name it, and list its portals or entry points)_

---

## 1. Sources

| Source ID | File | State | Last verified | Answers |
|---|---|---|---|---|
| `env` | `../base-test/execute.env.md` | unbound | - | Which environment we test, its URLs, where its credentials come from |
| `test-data` | `../base-test/test-centralized.md` | unbound | - | The accounts and records a test may use |
| `navigation` | `../base-test/navigation-map.md` | unbound | - | Real routes, page-versus-modal behaviour, viewports |
| `auth` | `../base-test/01-auth-steps.md` | unbound | - | Reusable login preconditions per role |
| `env-check` | `../base-test/03-environment-check.md` | unbound | - | The smoke check that says the environment is fit to test |
| `api-baseline` | `../base-test/04-api-baseline.md` | unbound | - | Setup or verification outside the UI |
| `cleanup` | `../base-test/05-cleanup-steps.md` | unbound | - | Teardown that leaves the environment as it was found |
| `domain` | `../qa-docs/` | unbound | - | Feature and business-rule knowledge: what the product should do, what it was observed to do, what is still unknown |

**`State` values:** `active` (read it, trust it) - `stale` (read it, date every fact
taken from it) - `missing` (declared but absent: name the gap, never invent the content)
- `unbound` (no file chosen yet).

Every row starts `unbound`. Set a row to `active` and fill in `Last verified` once the
file exists and someone has checked it against the running application. Run
`stlc-init-workspace` for `env` and `test-data`, and `stlc-baseline-generator` for the
rest.

---

## 2. Load sets

What each skill reads. **Always** is paid for on every run - keep it short.

| Skill | Always | When relevant |
|---|---|---|
| `stlc-requirements-analyst` | `domain` | - |
| `stlc-test-plan-designer` | `domain` | `env` |
| `stlc-testcase-designer` | `test-data`, `navigation`, `domain` | `env`, `auth` |
| `stlc-testcase-reviewer` | `domain`, `navigation` | `test-data` |
| `stlc-manual-executor` | `env`, `test-data`, `navigation` | `env-check`, `cleanup`, `api-baseline` |
| `stlc-bug-reporter` | `env` | `navigation`, `domain` |
| `stlc-test-reporter` | `env` | - |
| `stlc-baseline-generator` | - | all - it *writes* these files |
| `agent-coordination` | - | - |
| `tracker-*` | - | - |

A skill absent from this table reads no standing knowledge.

---

## 3. Where to start

Bind `env` and `test-data` first - nothing can be executed without them. Then
`navigation`, which is what stops an execution run losing time on wrong routes.

`domain` is the one source that grows every cycle: it holds what the team has learned
about the product's features, separating **what a spec says** from **what a run
observed** from **what is still unknown**. Leaving it `unbound` means every test cycle
re-derives the same business rules from the ticket, and asks the developer questions that
were already answered once.

---

## Rules

- **Never put knowledge in this file.** It names files; it never holds their content.
  A fact that lives only here is a fact no skill can find.
- **Never hardcode a credential here.** Credentials belong in the gitignored `/.env`;
  the `env` source names the variables.
- `Last verified` is a promise. Change it only when someone has actually re-checked the
  file against the running application, and set the source to `stale` when the
  environment moves under it.
- A source that turns out to be wrong is set to `stale` immediately, before the fix.
  A wrong `active` source is worse than a `missing` one.
- When a source is added, removed, or re-bound, update section 1 and section 2 in the
  same edit.
KEOF
  echo "  Created : qa-artifacts/qa-config/knowledge.md  (edit this — bind your knowledge sources)"
else
  echo "  Exists  : qa-artifacts/qa-config/knowledge.md"
fi

