# init.ps1 — Initialise qa-artifacts workspace (Windows / PowerShell)
# Run from the project root: .\.claude\skills\stlc-init-workspace\scripts\init.ps1
# Safe to re-run — existing files are never overwritten.

param(
  [switch]$Reset   # Pass -Reset to delete and recreate qa-artifacts/
)

$base = (Resolve-Path (Join-Path $PSScriptRoot "..\..\..\..")).Path   # repo root: scripts/ -> stlc-init-workspace/ -> skills/ -> .claude/ -> root

# ── Optionally reset ────────────────────────────────────────────────────────
if ($Reset -and (Test-Path "$base\qa-artifacts")) {
  Remove-Item -Recurse -Force "$base\qa-artifacts"
  Write-Host "qa-artifacts/ removed."
}

# ── Folder list ─────────────────────────────────────────────────────────────
$folders = @(
  "requirements",
  "qa-artifacts\0-sprint-tickets",
  "qa-artifacts\1-requirements-analysis",
  "qa-artifacts\2-test-plan",
  "qa-artifacts\3-test-cases",
  "qa-artifacts\4-execution-results",
  "qa-artifacts\4-execution-results\screenshots",
  "qa-artifacts\5-testing-report",
  "qa-artifacts\base-test",
  "qa-artifacts\qa-config",
  "qa-artifacts\qa-docs"
)

foreach ($f in $folders) {
  $path = Join-Path $base $f
  if (-not (Test-Path $path)) {
    New-Item -ItemType Directory -Path $path -Force | Out-Null
    Write-Host "  Created : $f"
  } else {
    Write-Host "  Exists  : $f"
  }
}

