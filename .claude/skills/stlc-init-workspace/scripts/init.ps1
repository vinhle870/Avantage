# ── qa-config\knowledge.md - project knowledge registry ----------------------
$knowledgeRegistry = Join-Path $base "qa-artifacts\qa-config\knowledge.md"
if (-not (Test-Path $knowledgeRegistry)) {
  Set-Content -Path $knowledgeRegistry -Encoding UTF8 -Value @'
# Project Knowledge Registry

**Owned by the QA on this project - not by the skill framework.**

Every skill that needs standing knowledge about the application under test reads this
file *first* to decide which files to open. Skills never hardcode a knowledge path;
they name a **source ID** (`navigation`, `domain`) and let this table resolve it.

The resolution rule, the source-ID vocabulary and the rules for skill authors are in
`.claude/skills/knowledge-sources.md`. This file holds only *this project's* answers.

**Application under test:** _(name it, and list its portals or entry points)_

---

## 1. Sources

| Source ID | File | State | Last verified | Answers |
|---|---|---|---|---|
| `env` | `../base-test/execute.env.md` | unbound | - | Which environment we test, its URLs, where its credentials come from |
| `test-data` | `../base-test/test-centralized.md` | unbound | - | The accounts and records a test may use |
| `navigation` | `../base-test/navigation-map.md` | unbound | - | Real routes, page-versus-modal behaviour, viewports |
| `auth` | `../base-test/01-auth-steps.md` | unbound | - | Reusable login preconditions per role |
| `env-check` | `../base-test/03-environment-check.md` | unbound | - | The smoke check that says the environment is fit to test |
| `api-baseline` | `../base-test/04-api-baseline.md` | unbound | - | Setup or verification outside the UI |
| `cleanup` | `../base-test/05-cleanup-steps.md` | unbound | - | Teardown that leaves the environment as it was found |
| `domain` | `../qa-docs/` | unbound | - | Feature and business-rule knowledge: what the product should do, what it was observed to do, what is still unknown |

**`State` values:** `active` (read it, trust it) - `stale` (read it, date every fact
taken from it) - `missing` (declared but absent: name the gap, never invent the content)
- `unbound` (no file chosen yet).

Every row starts `unbound`. Set a row to `active` and fill in `Last verified` once the
file exists and someone has checked it against the running application. Run
`stlc-init-workspace` for `env` and `test-data`, and `stlc-baseline-generator` for the
rest.

---

## 2. Load sets

What each skill reads. **Always** is paid for on every run - keep it short.

| Skill | Always | When relevant |
|---|---|---|
| `stlc-requirements-analyst` | `domain` | - |
| `stlc-test-plan-designer` | `domain` | `env` |
| `stlc-testcase-designer` | `test-data`, `navigation`, `domain` | `env`, `auth` |
| `stlc-testcase-reviewer` | `domain`, `navigation` | `test-data` |
| `stlc-manual-executor` | `env`, `test-data`, `navigation` | `env-check`, `cleanup`, `api-baseline` |
| `stlc-bug-reporter` | `env` | `navigation`, `domain` |
| `stlc-test-reporter` | `env` | - |
| `stlc-baseline-generator` | - | all - it *writes* these files |
| `agent-coordination` | - | - |
| `tracker-*` | - | - |

A skill absent from this table reads no standing knowledge.

---

## 3. Where to start

Bind `env` and `test-data` first - nothing can be executed without them. Then
`navigation`, which is what stops an execution run losing time on wrong routes.

`domain` is the one source that grows every cycle: it holds what the team has learned
about the product's features, separating **what a spec says** from **what a run
observed** from **what is still unknown**. Leaving it `unbound` means every test cycle
re-derives the same business rules from the ticket, and asks the developer questions that
were already answered once.

---

## Rules

- **Never put knowledge in this file.** It names files; it never holds their content.
  A fact that lives only here is a fact no skill can find.
- **Never hardcode a credential here.** Credentials belong in the gitignored `/.env`;
  the `env` source names the variables.
- `Last verified` is a promise. Change it only when someone has actually re-checked the
  file against the running application, and set the source to `stale` when the
  environment moves under it.
- A source that turns out to be wrong is set to `stale` immediately, before the fix.
  A wrong `active` source is worse than a `missing` one.
- When a source is added, removed, or re-bound, update section 1 and section 2 in the
  same edit.
'@
  Write-Host "  Created : qa-artifacts\qa-config\knowledge.md  (edit this - bind your knowledge sources)"
} else {
  Write-Host "  Exists  : qa-artifacts\qa-config\knowledge.md"
}

