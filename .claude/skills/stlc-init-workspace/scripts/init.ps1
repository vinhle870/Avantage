"@

  "qa-artifacts\3-test-cases\README.md" = @"
# 3 — Test Cases

**Generated by:** stlc-testcase-designer
**Output file:** test-cases.md
"@

  "qa-artifacts\4-execution-results\README.md" = @"
# 4 — Execution Results

