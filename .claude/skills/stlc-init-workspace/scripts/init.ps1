  "qa-artifacts\qa-docs\README.md" = @"
# qa-docs/ — domain and feature knowledge

This folder is the ``domain`` knowledge source named in ``qa-config/knowledge.md``.
Write one file per feature or business area, and keep three things apart in each:

- **What the spec says** — cite the ticket or requirement.
- **What a run observed** — cite the test case, the date, and the screenshot.
- **What is still unknown** — cite the open question and who owns it.

A test-case designer that cannot tell those apart will write cases that assert a bug is
correct behaviour. Nothing here is generated: this is the knowledge the team accumulates,
and it is the only artifact folder that outlives a single test cycle.

Once the first file exists, set the ``domain`` row in ``qa-config/knowledge.md`` to
``active``.
"@

  "qa-artifacts\5-testing-report\README.md" = @"
# 5 — Testing Report

**Generated by:** stlc-bug-reporter + stlc-test-reporter
**Output files:** bug-report.md · test-report.md
"@
}

foreach ($entry in $readmes.GetEnumerator()) {
  $path = Join-Path $base $entry.Key
  if (-not (Test-Path $path)) {
    Set-Content -Path $path -Value $entry.Value -Encoding UTF8
    Write-Host "  README  : $($entry.Key)"
  }
}

